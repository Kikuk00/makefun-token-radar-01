// Token Radar — the value model (radar-2).
//
// One sealed snapshot in, one ranked board out. Every number below is derived
// from the snapshot's own figures; no protocol name is ever special-cased and
// the same function scores every row.
//
// The question the board answers: if a protocol that records no token issued
// one tomorrow and the market priced it like the tokens that already trade,
// what would it be worth? The anchor is the market itself: for each category
// we take the median market-cap-to-TVL ratio of the live-token protocols in
// that category, and a pre-token protocol's base value is its TVL times that
// peer ratio. A category with too few live peers falls back to the global
// median ratio. Three adjustments then apply, all from the snapshot:
//
//   growth    = clamp(change_7d, -60, +120) per cent
//   growthMult   = 1 + growth/100 * 0.5        (momentum, capped so one hot week cannot dominate)
//   maturityMult = 0.6 + min(age_days, 1095)/1095 * 0.4   (older, longer-running protocols earn more;
//                                                        unknown listing date counts as 365 days)
//   breadthMult  = 1 + 0.03 * min(chains - 1, 5)          (multi-chain reach, at most +15%)
//
//   implied_value_usd = round(tvl_usd * peer_ratio * growthMult * maturityMult * breadthMult)
//
// The board ranks every rankable pre-token protocol: the whole watchlist
// (the floor) plus every other pre-token protocol the snapshot holds that is
// not a wrapped, staked or bridged product of a token that already trades.
// Protocols whose token already trades are never ranked; they appear only
// in the Live view, at the market's own value, so the board always separates
// "still to come" from "already trading". A protocol "records no token" in
// DefiLlama's record — that is never a claim that it has none.

/** One protocol entry: exactly the ten fields the sealed snapshot carries. */
